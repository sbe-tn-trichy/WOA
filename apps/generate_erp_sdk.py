"""Generate ERP resource methods from local OpenAPI YAML files (no network)."""
from __future__ import annotations

import argparse
import hashlib
import json
import keyword
from pathlib import Path
import re

import yaml

METHODS = {"get", "post", "put", "patch", "delete", "head", "options"}
ROOT = Path(__file__).resolve().parents[1]


def identifier(value: str) -> str:
    """Convert spec names into valid, deterministic Python identifiers."""
    value = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", value)
    value = re.sub(r"\W+", "_", value).strip("_").lower()
    if not value or value[0].isdigit() or keyword.iskeyword(value):
        value = "api_" + value
    return value


def resolve(document: dict, value: dict) -> dict:
    """Resolve local parameter references; reject unsupported external refs."""
    seen = set()
    while "$ref" in value:
        ref = value["$ref"]
        if not ref.startswith("#/") or ref in seen:
            raise ValueError(f"Unsupported or cyclic reference: {ref}")
        seen.add(ref)
        value = document
        for part in ref[2:].split("/"):
            value = value[part.replace("~1", "/").replace("~0", "~")]
    return value


def generate(source: Path, destination: Path) -> dict:
    """Write deterministic resources and provenance after validating every file."""
    lines = ['"""Generated by apps/generate_erp_sdk.py; do not edit manually."""',
             "from typing import Any", "from .resource import ERPResource", ""]
    registry = []
    manifest = {}
    for path in sorted(source.glob("*.yml")):
        raw = path.read_bytes()
        document = yaml.safe_load(raw)
        name = identifier(path.stem)
        cls = "".join(part.title() for part in name.split("_"))
        if name in {entry[0] for entry in registry}:
            raise ValueError(f"Duplicate resource name: {name}")
        registry.append((name, cls))
        lines.extend([f"class {cls}(ERPResource):", f'    """{name} ERP operations."""'])
        operations = []
        names = set()
        for endpoint, item in document.get("paths", {}).items():
            for verb, operation in item.items():
                if verb not in METHODS:
                    continue
                method = identifier(operation["operationId"])
                if method in names or hasattr(object, method) or method in {"_request", "client"}:
                    raise ValueError(f"Conflicting operation: {path.name}: {method}")
                names.add(method)
                servers = operation.get("servers", item.get("servers", document["servers"]))
                server = servers[0]["url"]
                match = re.fullmatch(r"https://www\.zohoapis\.in/erp/(v\d+)", server)
                if not match:
                    raise ValueError(f"Unsupported ERP server: {server}")
                version = match[1]
                placeholders = list(dict.fromkeys(re.findall(r"\{([^}]+)\}", endpoint)))
                args = [identifier(p) for p in placeholders]
                reserved = {"self", "body", "params", "headers", "files", "stream", "timeout"}
                if len(args) != len(set(args)) or reserved.intersection(args):
                    raise ValueError(f"Conflicting path parameters: {endpoint}")
                parameters = {}
                for parameter in item.get("parameters", []) + operation.get("parameters", []):
                    parameter = resolve(document, parameter)
                    parameters[(parameter["in"], parameter["name"])] = parameter
                required = [p["name"] for p in parameters.values()
                            if p["in"] == "query" and p.get("required") and p["name"] != "organization_id"]
                required_headers = [p["name"] for p in parameters.values()
                                    if p["in"] == "header" and p.get("required")]
                request = resolve(document, operation.get("requestBody", {}))
                media = list(request.get("content", {}))
                signature = ", ".join(["self"] + [f"{arg}: str" for arg in args] + ["*",
                    "body: dict[str, Any] | None = None", "params: dict[str, Any] | None = None",
                    "headers: dict[str, Any] | None = None", "files: dict[str, Any] | None = None",
                    "stream: bool = False", "timeout: int | None = None"])
                doc = operation.get("summary", method) + "\n\nOperation: " + operation["operationId"]
                doc += "\nOAuth scopes: " + ", ".join(s for scopes in operation.get("security", []) for values in scopes.values() for s in values)
                lines.extend([f"    def {method}({signature}) -> object:", f"        {doc!r}",
                    f"        return self._request({verb.upper()!r}, {endpoint!r}, {version!r},",
                    f"            path_values={{{', '.join(repr(p) + ': ' + a for p, a in zip(placeholders, args))}}},",
                    f"            required_query={required!r}, required_headers={required_headers!r}, media={media!r},",
                    f"            body_required={bool(request.get('required'))!r}, body=body, params=params,",
                    "            headers=headers, files=files, stream=stream, timeout=timeout)", ""])
                operations.append({"name": method, "operation_id": operation["operationId"],
                                   "method": verb.upper(), "path": endpoint, "version": version,
                                   "path_parameters": placeholders, "required_query": required,
                                   "required_headers": required_headers, "media": media,
                                   "body_required": bool(request.get("required"))})
        if not operations:
            raise ValueError(f"No operations in {path.name}")
        manifest[name] = {"source": path.name, "sha256": hashlib.sha256(raw).hexdigest(), "operations": operations}
    if not registry:
        raise ValueError(f"No .yml definitions in {source}")
    lines.extend(["class ERPResources:", '    """Typed resource attributes available on ZohoERPAPI."""'])
    lines.extend(f"    {name}: {cls}" for name, cls in registry)
    lines.extend(["", "RESOURCE_TYPES = {"])
    lines.extend(f"    {name!r}: {cls}," for name, cls in registry)
    lines.append("}\n")
    text = "\n".join(lines)
    compile(text, "generated.py", "exec")
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "generated.py").write_text(text, encoding="utf-8", newline="\n")
    (destination / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Folder containing ERP OpenAPI .yml definitions")
    args = parser.parse_args()
    manifest = generate(args.source, ROOT / "src/zoho/erp")
    print(f"Generated {len(manifest)} resources and {sum(len(r['operations']) for r in manifest.values())} operations.")


if __name__ == "__main__":
    main()
