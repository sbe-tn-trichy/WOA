"""Generate the Analytics SDK from a local checkout's v2.0 OpenAPI directory."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
HEADER = '"""Generated by apps/sdk_tools/generate_analytics_sdk.py. Do not edit manually."""'
DOMAINS = {
    "administration": ("org_management", "user_groups", "share_publish", "schedules_alerts"),
    "workspace": (
        "workspace_management", "data_modeling_schema", "data_operations",
        "views_management", "reports_dashboards", "dsml",
    ),
}
METHODS = {"get", "post", "put", "patch", "delete"}
MEDIA_LOCATIONS = {
    "application/x-www-form-urlencoded": "form",
    "multipart/form-data": "multipart",
}


def snake_case(name: str) -> str:
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).replace("-", "_").lower()


def operation_arguments(
    document: dict[str, Any], operation: dict[str, Any],
) -> tuple[str | None, bool, bool, bool, bool]:
    location = None
    config_required = False
    destination_org = False
    for parameter in operation.get("parameters", []):
        if "$ref" in parameter:
            prefix = "#/components/parameters/"
            ref = parameter["$ref"]
            if not ref.startswith(prefix):
                raise ValueError(f"Unsupported parameter reference: {ref}")
            parameter = document["components"]["parameters"][ref.removeprefix(prefix)]
        match parameter["in"], parameter["name"]:
            case "query", "CONFIG":
                location = "query"
                config_required = bool(parameter.get("required"))
            case "header", "ZANALYTICS-DEST-ORGID":
                destination_org = True
            case ("header", "ZANALYTICS-ORGID") | ("path", _):
                continue
            case _:
                raise ValueError(f"Unsupported parameter: {parameter['name']}")

    inline_data = False
    if body := operation.get("requestBody"):
        if location or len(body["content"]) != 1:
            raise ValueError(f"Unsupported request body for {operation['operationId']}")
        media, content = next(iter(body["content"].items()))
        location = MEDIA_LOCATIONS[media]
        schema = content["schema"]
        properties = set(schema["properties"])
        expected = {"CONFIG"} if location == "form" else {"CONFIG", "FILE"}
        inline_data = location == "multipart" and "DATA" in properties
        if inline_data:
            expected.add("DATA")
        if properties != expected:
            raise ValueError(f"Unsupported request fields for {operation['operationId']}")
        config_required = bool(body.get("required"))
    return location, config_required, location == "multipart", inline_data, destination_org


def render_operation(
    document: dict[str, Any], path: str, verb: str, operation: dict[str, Any],
) -> tuple[dict[str, Any], list[str]]:
    if not path.startswith("/restapi/v2/"):
        raise ValueError(f"Unexpected Analytics v2 path: {path}")
    endpoint = path.removeprefix("/restapi/v2/")
    method = verb.upper()
    operation_id = operation["operationId"]
    name = snake_case(operation_id)
    path_parameters = re.findall(r"{([\w-]+)}", endpoint)
    path_values = ", ".join(f"{key!r}: {snake_case(key)}" for key in path_parameters)
    location, required, upload, inline_data, destination_org = operation_arguments(document, operation)
    signature = ["self", *(f"{snake_case(key)}: str" for key in path_parameters), "*"]
    arguments = [f"path_values={{{path_values}}}"]
    if location:
        default = "" if required else " | None = None"
        signature.append(f"config: dict[str, Any]{default}")
        arguments.extend(["config=config", f"config_location={location!r}"])
    if upload:
        signature.append("upload: Any = None" if inline_data else "upload: Any")
        arguments.append("upload=upload")
    if inline_data:
        signature.append("inline_data: str | None = None")
        arguments.append("inline_data=inline_data")
    if destination_org:
        signature.append("destination_org_id: str | None = None")
        arguments.append("destination_org_id=destination_org_id")

    signature.extend(["stream: bool = False", "timeout: int | None = None"])
    scopes = [
        scope for item in operation.get("security", [])
        for scope_list in item.values() for scope in scope_list
    ]
    doc = f"{operation['summary']}\n\n{method} {path}\nOAuth scopes: {', '.join(scopes)}"
    lines = ["", f"    def {name}({', '.join(signature)}) -> Any:", f"        {doc!r}"]
    if required:
        lines.extend(["        if config is None:", "            raise ValueError('config is required')"])
    if operation_id == "getWorkspaceSecretKey":
        lines.extend([
            "        regenerate = config.get('regenerateKey', False) if isinstance(config, dict) else False",
            "        if not isinstance(regenerate, bool):",
            "            raise ValueError('regenerateKey must be a boolean')",
        ])
        arguments.append("is_mutation=regenerate")
    lines.extend([
        "        return self._request_operation(",
        f"            {method!r}, {endpoint!r},",
        f"            {', '.join(arguments)},",
        "            stream=stream, timeout=timeout,",
        "        )",
    ])
    return {
        "name": name, "operation_id": operation_id, "method": method, "path": path,
        "category": operation["tags"][0], "scopes": scopes,
    }, lines


def generate(source: Path, destination: Path) -> dict[str, Any]:
    """Write deterministic wrappers and the source/operation manifest."""
    modules = {Path("resources/__init__.py"): [HEADER]}
    imports = []
    bindings = []
    manifest = {}
    routes = set()
    for package, domains in DOMAINS.items():
        modules[Path("resources", package, "__init__.py")] = [HEADER]
        for domain in domains:
            spec = source / (domain.replace("_", "-") + "-grouped-api.json")
            raw = spec.read_bytes()
            document = json.loads(raw)
            class_name = "".join(part.title() for part in domain.split("_"))
            lines = [HEADER, "from typing import Any", "from ...resource import AnalyticsOperationResource",
                     "", "", f"class {class_name}(AnalyticsOperationResource):",
                     f"    \"\"\"{domain.replace('_', ' ').capitalize()} operations.\"\"\""]
            names = set()
            records = []
            for path, path_item in document["paths"].items():
                for verb, operation in path_item.items():
                    if verb not in METHODS:
                        raise ValueError(f"Unsupported path item key {verb!r} for {path}")
                    record, operation_lines = render_operation(document, path, verb, operation)
                    route = (verb, re.sub(r"{[^}]+}", "{}", path))
                    if route in routes or record["name"] in names:
                        raise ValueError(f"Duplicate Analytics wrapper for {verb.upper()} {path}")
                    routes.add(route)
                    names.add(record["name"])
                    records.append(record)
                    lines.extend(operation_lines)
            module = Path("resources", package, f"{domain}.py")
            modules[module] = lines
            manifest[domain] = {
                "source": spec.name, "sha256": hashlib.sha256(raw).hexdigest(),
                "module": module.as_posix(), "operations": records,
            }
            imports.append(f"from .resources.{package}.{domain} import {class_name}")
            bindings.append((domain, class_name))

    lines = [HEADER, "from typing import TYPE_CHECKING", *imports, "",
             "if TYPE_CHECKING:", "    from ..client import ZohoAnalyticsAPI", "", "",
             "class AnalyticsResources:", '    """Typed domain resources for the Analytics v2 API."""', "",
             '    def __init__(self, client: "ZohoAnalyticsAPI") -> None:']
    lines.extend(f"        self.{domain} = {class_name}(client)" for domain, class_name in bindings)
    lines.extend(["", "", "RESOURCE_TYPES = {"])
    lines.extend(f"    {domain!r}: {class_name}," for domain, class_name in bindings)
    lines.append("}")
    modules[Path("generated.py")] = lines

    outputs = {path: "\n".join(lines) + "\n" for path, lines in modules.items()}
    for path, contents in outputs.items():
        compile(contents, str(path), "exec")
    outputs[Path("manifest.json")] = json.dumps(manifest, indent=2) + "\n"
    for path, contents in outputs.items():
        output = destination / path
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(contents, encoding="utf-8", newline="\n")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Local analytics-oas/v2.0 directory")
    args = parser.parse_args()
    manifest = generate(args.source, ROOT / "src/zoho/analytics/openapi")
    print(f"Generated {len(manifest)} domains and {sum(len(domain['operations']) for domain in manifest.values())} operations.")


if __name__ == "__main__":
    main()
